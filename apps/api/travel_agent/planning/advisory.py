def pool(db: Any, scope: str, sid: str, p: dict[str, Any]) -> list[Activity]:
    """Revalidate provided candidates, never revive a withdrawn snapshot."""
    values = {a["activity_id"]: a for a in p.get("activity_pool", [])}
    values.update({a["activity_id"]: a for a in p["draft"]["activities"]})
    if p.get("demo") == SYNTHETIC:
        source = {a.activity_id: a for a in fixture()[0]}
        result = []
        for v in values.values():
            a = Activity.model_validate(v)
            orig = source.get(a.activity_id)
            if not orig or (a.name, a.region, a.provenance) != (
                orig.name,
                orig.region,
                orig.provenance,
            ):
                raise ValueError("PLANNING_SYNTHETIC_ONLY")
            result.append(a)
        return result
    if p.get("knowledge_mode"):
        from travel_agent.knowledge.planning import verify

        result = []
        for v in values.values():
            context = deepcopy(p)
            context["draft"]["activities"] = [v]
            try:
                verify(db, scope, context)
                result.append(Activity.model_validate(v))
            except ValueError:
                continue
        return result
    from .materials import references, activities, candidate_from_name, same_conditions
    from .discovery import checked, as_activity

    refs = references(db, scope, sid)
    supported = {
        a.activity_id: a
        for a in activities(
            refs, p["destination"], PlanDraft.model_validate(p["draft"]).spatial.intent
        )
    }
    try:
        supported.update(
            {
                i: as_activity(v)
                for i, v in checked(db, scope, sid, p).items()
                if not v["quarantined"]
                and v["identity_status"] == "CHECKED"
                and v["spatial_status"] != "MISMATCH"
            }
        )
    except ValueError:
        pass
    by_id = {r["claim_id"]: r for r in refs}
    for key, value in values.items():
        current = Activity.model_validate(value)
        if (
            key not in supported
            and current.provenance == "SOURCE_REFERENCE"
            and current.evidence_ids
            and not current.discovery_ids
            and not current.knowledge_refs
            and set(current.evidence_ids) <= by_id.keys()
        ):
            # New same-name references may change the aggregate candidate ID.
            # Revalidate the original exact subset; never substitute newer citations.
            try:
                bound = candidate_from_name(
                    current.name, [by_id[i] for i in current.evidence_ids],
                    p["destination"], PlanDraft.model_validate(p["draft"]).spatial.intent,
                )
                if (bound.activity_id, bound.region, bound.reference_kinds) == (
                    current.activity_id, current.region, current.reference_kinds,
                ):
                    supported[key] = bound
            except ValueError:
                pass
        if key in supported:
            original = supported[key]
            if (current.name, current.evidence_ids, current.discovery_ids) == (
                original.name,
                original.evidence_ids,
                original.discovery_ids,
            ) and same_conditions(current.conditions, original.conditions):
                supported[key] = current
    return list(supported.values())


